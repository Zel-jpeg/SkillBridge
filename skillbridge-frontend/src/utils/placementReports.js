import api from '../api/axios'

const REPORT_META = {
  company_placements: {
    subtitle: 'Company / Position Placement Report',
    slug: 'company-placements',
  },
  student_placements: {
    subtitle: 'Student Placement Report',
    slug: 'student-placements',
  },
  placement_history: {
    subtitle: 'Placement History Report',
    slug: 'placement-history',
  },
}

const STATUS_LABELS = {
  suggested: 'Suggested',
  approved: 'Approved',
  removed: 'Removed',
  rejected: 'Rejected',
}

const FILTER_LABELS = {
  status: 'Status',
  company_id: 'Company',
  position_id: 'Position',
  batch_id: 'Batch',
  course: 'Course',
  area: 'Company area',
  date_field: 'Date field',
  date_from: 'From',
  date_to: 'To',
}

const clean = value => value == null || value === '' ? '—' : String(value)
const percent = value => value == null ? '—' : `${Number(value).toFixed(1)}%`
const distance = value => value == null ? '—' : `${Number(value).toFixed(1)} km`
const person = value => value?.name || '—'

function dateTime(value) {
  if (!value) return '—'
  return new Intl.DateTimeFormat('en-PH', {
    timeZone: 'Asia/Manila',
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(new Date(value))
}

function reportDate(payload) {
  return new Date(Date.parse(payload.generated_at) + 8 * 3600000).toISOString().slice(0, 10)
}

function filterDescription(payload, labels = {}) {
  const values = []
  Object.entries(payload.filters || {}).forEach(([key, value]) => {
    if (!FILTER_LABELS[key] || value == null || value === '' || value === 'all') return
    let display = labels[key]?.[value] || value
    if (key === 'date_field') display = value === 'approved_at' ? 'Approved date' : 'Created date'
    values.push(`${FILTER_LABELS[key]}: ${display}`)
  })
  return values.length ? values.join('  |  ') : 'No filters (all placement records)'
}

function drawReportHeader(doc, payload, filterLabels) {
  const width = doc.internal.pageSize.getWidth()
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  const authorLines = doc.splitTextToSize(`Generated by: ${person(payload.generated_by)} (${clean(payload.generated_by?.role)})`, 100)
  const headerHeight = Math.max(27, 20 + authorLines.length * 3)
  doc.setFillColor(20, 83, 45)
  doc.rect(0, 0, width, headerHeight, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.text('SkillBridge OJT Placement Report', 12, 11)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text(REPORT_META[payload.report_type].subtitle, 12, 19)
  doc.setFontSize(7.5)
  doc.text(`Generated (PHT): ${dateTime(payload.generated_at)}`, width - 12, 10, { align: 'right' })
  doc.text(authorLines, width - 12, 17, { align: 'right' })

  doc.setTextColor(55, 65, 81)
  doc.setFont('helvetica', 'bold')
  doc.text('FILTERS USED', 12, headerHeight + 7)
  doc.setFont('helvetica', 'normal')
  const filterLines = doc.splitTextToSize(filterDescription(payload, filterLabels), width - 24)
  doc.text(filterLines, 12, headerHeight + 12)

  const summaryY = headerHeight + 16 + (filterLines.length * 3)
  const summaryItems = [
    ['Records', payload.summary.total_records],
    ['Students', payload.summary.unique_students],
    ['Companies', payload.summary.unique_companies],
    ['Positions', payload.summary.unique_positions],
    ['Approved records', payload.summary.status_counts.approved],
    ['Remaining slots', payload.summary.remaining_slots],
  ]
  const gap = 2
  const boxWidth = (width - 24 - gap * (summaryItems.length - 1)) / summaryItems.length
  summaryItems.forEach(([label, value], index) => {
    const x = 12 + index * (boxWidth + gap)
    doc.setFillColor(242, 247, 244)
    doc.roundedRect(x, summaryY, boxWidth, 14, 1.5, 1.5, 'F')
    doc.setTextColor(20, 83, 45)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(10)
    doc.text(clean(value), x + 3, summaryY + 6)
    doc.setTextColor(75, 85, 99)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(6.5)
    doc.text(label, x + 3, summaryY + 11)
  })
  doc.setFontSize(7)
  doc.text(doc.splitTextToSize(payload.capacity_scope || 'Capacity covers reported positions; occupancy includes all current approvals.', width - 24), 12, summaryY + 19)
  return summaryY + 26
}

function tableTheme(overrides = {}) {
  return {
    theme: 'grid',
    margin: { left: 12, right: 12, bottom: 16 },
    styles: {
      font: 'helvetica', fontSize: 6.4, cellPadding: 1.7,
      overflow: 'linebreak', valign: 'middle', textColor: [55, 65, 81],
    },
    headStyles: {
      fillColor: [31, 41, 55], textColor: [255, 255, 255],
      fontStyle: 'bold', fontSize: 6.5,
    },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    ...overrides,
  }
}

function addCompanyTables(doc, autoTable, records, startY) {
  const groups = new Map()
  records.forEach(record => {
    const key = `${record.company.id}:${record.position.id}`
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push(record)
  })
  let y = startY
  if (!groups.size) {
    autoTable(doc, tableTheme({
      startY: y,
      head: [['Company / Position', 'Placement records']],
      body: [['—', 'No placement records match the selected filters.']],
    }))
    return
  }
  groups.forEach(group => {
    const first = group[0]
    if (y > doc.internal.pageSize.getHeight() - 42) {
      doc.addPage()
      y = 18
    }
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(9)
    doc.setTextColor(20, 83, 45)
    const heading = doc.splitTextToSize(`${first.company.name} - ${first.position.title}`, doc.internal.pageSize.getWidth() - 24)
    doc.text(heading, 12, y)
    y += (heading.length - 1) * 4
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7)
    doc.setTextColor(75, 85, 99)
    const capacity = `${first.position.approved_count} approved / ${first.position.slots_available} slots / ${first.position.remaining_slots} remaining`
    const detail = doc.splitTextToSize(`${first.company.address_text || 'Address not provided'} | ${capacity}`, doc.internal.pageSize.getWidth() - 24)
    doc.text(detail, 12, y + 5)
    y += (detail.length - 1) * 3
    autoTable(doc, tableTheme({
      startY: y + 8,
      head: [[
        'Student', 'School ID', 'Course', 'Batch', 'Status', 'Hybrid match',
        'Category fit', 'NLP fit', 'Location fit', 'Distance', 'Approved at', 'Remarks',
      ]],
      body: group.map(record => [
        record.student.name,
        clean(record.student.school_id),
        clean(record.student.course),
        clean(record.batch?.name),
        STATUS_LABELS[record.status] || record.status,
        percent(record.match_score_at_assignment),
        percent(record.category_score_component_at_assignment),
        percent(record.nlp_score_component_at_assignment),
        percent(record.location_score_component_at_assignment),
        distance(record.distance_km_at_assignment),
        dateTime(record.approved_at),
        clean(record.remarks),
      ]),
      columnStyles: {
        0: { cellWidth: 28 }, 1: { cellWidth: 16 }, 2: { cellWidth: 15 },
        3: { cellWidth: 21 }, 4: { cellWidth: 16 }, 5: { cellWidth: 14 },
        6: { cellWidth: 14 }, 7: { cellWidth: 14 }, 8: { cellWidth: 14 },
        9: { cellWidth: 16 }, 10: { cellWidth: 27 }, 11: { cellWidth: 'auto' },
      },
    }))
    y = doc.lastAutoTable.finalY + 11
  })
}

