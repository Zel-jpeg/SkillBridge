function addSignaturesAndFooters(doc) {
  const height = doc.internal.pageSize.getHeight()
  const width = doc.internal.pageSize.getWidth()
  let y = (doc.lastAutoTable?.finalY || 50) + 23
  if (y > height - 30) {
    doc.addPage()
    y = 28
  }
  const labels = ['Prepared by', 'Checked by', 'Approved by']
  const sectionWidth = (width - 34) / 3
  labels.forEach((label, index) => {
    const x = 12 + index * (sectionWidth + 5)
    doc.setDrawColor(107, 114, 128)
    doc.line(x, y, x + sectionWidth, y)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7)
    doc.setTextColor(75, 85, 99)
    doc.text(label, x + sectionWidth / 2, y + 5, { align: 'center' })
  })

  const pages = doc.getNumberOfPages()
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7)
    doc.setTextColor(107, 114, 128)
    doc.text('SkillBridge — Official OJT placement record', 12, height - 7)
    doc.text(`Page ${page} of ${pages}`, width - 12, height - 7, { align: 'right' })
  }
}

export async function fetchPlacementReport(filters) {
  const params = new URLSearchParams()
  Object.entries(filters).forEach(([key, value]) => {
    if (value != null && value !== '') params.set(key, value)
  })
  const response = await api.get(`/api/placements/reports/?${params.toString()}`)
  return response.data
}

export async function downloadPlacementPdf(payload, filterLabels = {}) {
  const [{ jsPDF }, autoTableModule] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
  ])
  const autoTable = autoTableModule.default
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' })
  const startY = drawReportHeader(doc, payload, filterLabels)
  if (payload.report_type === 'company_placements') {
    addCompanyTables(doc, autoTable, payload.records, startY)
  } else if (payload.report_type === 'student_placements') {
    addStudentTable(doc, autoTable, payload.records, startY)
  } else {
    addHistoryTable(doc, autoTable, payload.records, startY)
  }
  addSignaturesAndFooters(doc)
  doc.save(`skillbridge-${REPORT_META[payload.report_type].slug}-${reportDate(payload)}.pdf`)
}

