// Leaflet accepts HTML strings; encode data at that boundary, preserving the
// original stored value and ordinary React text rendering elsewhere.
export function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, character => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[character])
}
