def scope(page, label='Institute and program scope'):
    return page.get_by_role('group', name=label, exact=True)


def choose(page, institute, program=None):
    group = scope(page)
    group.get_by_label('Institute', exact=True).select_option(str(institute))
    if program:
        group.get_by_label('Program', exact=True).select_option(str(program))


def switch_to_list(page, name):
    toggle = page.get_by_role('group', name=name, exact=True)
    expect(toggle.get_by_role('button', name='Card view', exact=True)).to_have_attribute('aria-pressed', 'true')
    list_button = toggle.get_by_role('button', name='List view', exact=True)
    list_button.click()
    expect(list_button).to_have_attribute('aria-pressed', 'true')


def show_stored_images(context):
    context.route('**/storage/v1/object/public/**', lambda route: route.fulfill(
        body=(OUT / 'synthetic-images' / urlparse(route.request.url).path.split('/')[-1]).read_bytes(), content_type='image/webp'))


def attach_image(editor, name, color):
    image = BytesIO()
    Image.new('RGB', (60, 40), color).save(image, format='PNG')
    file_input = editor.locator('input[type=file]').and_(editor.get_by_label(name, exact=False))
    file_input.set_input_files({'name': 'synthetic-card.png', 'mimeType': 'image/png', 'buffer': image.getvalue()})


